#!/usr/bin/env python3
"""Unit checks for the skill adapter generator contract."""

from __future__ import annotations

import importlib.util
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
GENERATOR_PATH = ROOT / "scripts" / "generate-skill-adapters.py"


def load_generator():
    spec = importlib.util.spec_from_file_location("generate_skill_adapters", GENERATOR_PATH)
    if spec is None or spec.loader is None:
        raise RuntimeError("cannot load generator")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class SkillAdapterGeneratorTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.generator = load_generator()

    def test_generates_all_target_skill_adapters(self) -> None:
        outputs, manifest = self.generator.generated_outputs()
        self.assertEqual(len(outputs), 84)
        self.assertEqual(set(manifest["targets"]), {"codex", "opencode", "claude", "cursor"})
        for path in outputs:
            rel = path.relative_to(ROOT / "resources/default-workspace").as_posix()
            self.assertRegex(
                rel,
                r"^templates/skills/(codex|opencode|claude|cursor)/[a-z0-9-]+/SKILL[.]md$",
            )

    def test_generated_adapter_preserves_canonical_prefix(self) -> None:
        outputs, _manifest = self.generator.generated_outputs()
        canonical = (
            ROOT / "resources/default-workspace/skills/frontend-design/SKILL.md"
        ).read_text(encoding="utf-8")
        output = outputs[
            ROOT
            / "resources/default-workspace/templates/skills/codex/frontend-design/SKILL.md"
        ]
        self.assertTrue(output.startswith(canonical + "\n<!-- Generated by "))
        self.assertIn("### Codex Frontend Design", output)

    def test_claude_adapter_hoists_when_to_use(self) -> None:
        outputs, _manifest = self.generator.generated_outputs()
        claude = outputs[
            ROOT
            / "resources/default-workspace/templates/skills/claude/security-review/SKILL.md"
        ]
        codex = outputs[
            ROOT
            / "resources/default-workspace/templates/skills/codex/security-review/SKILL.md"
        ]
        claude_frontmatter = claude.split("---\n")[1]
        self.assertIn('when_to_use: "', claude_frontmatter)
        claude_body = claude.split("## Harness Adapter")[0]
        self.assertNotIn("## When To Use", claude_body)
        self.assertIn("## Do Not Use When", claude_body)
        self.assertIn("## When To Use", codex)
        self.assertNotIn("when_to_use:", codex)

    def test_overlay_frontmatter_merges_into_claude_adapter(self) -> None:
        outputs, _manifest = self.generator.generated_outputs()
        claude = outputs[
            ROOT
            / "resources/default-workspace/templates/skills/claude/release-check/SKILL.md"
        ]
        codex = outputs[
            ROOT
            / "resources/default-workspace/templates/skills/codex/release-check/SKILL.md"
        ]
        claude_frontmatter = claude.split("---\n")[1]
        self.assertIn("context: fork", claude_frontmatter)
        self.assertIn("agent: verifier", claude_frontmatter)
        self.assertIn("background: false", claude_frontmatter)
        self.assertNotIn("context: fork", codex)

    def test_manifest_outputs_match_generated_outputs(self) -> None:
        outputs, manifest = self.generator.generated_outputs()
        output_rels = {
            path.relative_to(ROOT / "resources/default-workspace").as_posix()
            for path in outputs
        }
        manifest_rels = {
            rel
            for skill in manifest["skills"].values()
            for rel in skill["outputs"].values()
        }
        self.assertEqual(output_rels, manifest_rels)


if __name__ == "__main__":
    unittest.main()
